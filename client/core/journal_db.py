# 兜底：当期刊名称未在估算表中时，使用该默认值（中等规模期刊）
DEFAULT_ANNUAL_VOLUME = 2000


def normalize_journal_name(name: str) -> str:
    """对期刊名称做归一化处理，便于匹配。"""
    n = name.strip().lower()
    # 去掉常见前缀标点
    n = n.lstrip(".,;:")
    # "the" 开头时去 the
    if n.startswith("the "):
        n = n[4:]
    return n.strip()


def resolve_journal_issn(name: str) -> list[str]:
    """在硬编码的期刊数据库中查找 ISSN。

    先用归一化后的名称精确匹配 COMMON_JOURNALS，
    失败后用别名映射到标准名再查。
    返回 ISSN 列表（print 和/或 online），找不到时返回空列表。
    """
    key = normalize_journal_name(name)
    if not key:
        return []

    # 1. 精确匹配
    if key in COMMON_JOURNALS:
        return COMMON_JOURNALS[key]

    # 2. 别名映射
    if key in JOURNAL_ALIASES:
        standard = JOURNAL_ALIASES[key]
        std_key = normalize_journal_name(standard)
        if std_key in COMMON_JOURNALS:
            return COMMON_JOURNALS[std_key]

    # 3. 部分匹配（用户输入是标准名的一部分 或 标准名包含用户输入）
    for known_key, issns in COMMON_JOURNALS.items():
        if key in known_key or known_key in key:
            return issns

    # 4. ISSN 号本身作为输入
    cleaned = name.strip().replace("-", "").replace(" ", "")
    if cleaned.isdigit() and len(cleaned) == 8:
        for issns in COMMON_JOURNALS.values():
            for issn in issns:
                if issn.replace("-", "") == cleaned:
                    return issns

    return []


def estimate_journal_volume(journal_name: str) -> int:
    """根据期刊名称估算年发文量。不区分大小写，精确匹配优先。"""
    key = normalize_journal_name(journal_name)
    if not key:
        return DEFAULT_ANNUAL_VOLUME

    # 精确匹配
    if key in ESTIMATED_VOLUME:
        return ESTIMATED_VOLUME[key]

    # 别名映射
    if key in JOURNAL_ALIASES:
        standard = JOURNAL_ALIASES[key]
        std_key = normalize_journal_name(standard)
        if std_key in ESTIMATED_VOLUME:
            return ESTIMATED_VOLUME[std_key]

    # 部分匹配
    for known_key, vol in ESTIMATED_VOLUME.items():
        if key in known_key or known_key in key:
            return vol

    return DEFAULT_ANNUAL_VOLUME
